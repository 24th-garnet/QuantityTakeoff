"""数量の根拠。**語彙を固定し、一番弱いものが勝つ。**

同じ壁面積でも、実測の壁厚から出した値と仮定した壁厚から出した値では、信じてよい
度合いが違う。上流は値そのものを素のまま書き、**仮定した値だけを名指しする**。
欄が無ければ実測。

```json
"basis": {"thickness": "既定", "ceiling_height": "代用"},
"basis_note": {"thickness": "RoomPlan は壁厚を返さない。作図上の 0.12 m"}
```

**語彙を固定する**のは、表記ゆれが混ざると機械で判定できなくなるため（単価表の
税区分や認定欄と同じ作法）。

## 未検出と未計測を分ける

**0 件を「無い」と読ませないため。** 開口 0 件には 3 つの意味がある。

| | |
|---|---|
| 欄が無い | 開口が本当に無い |
| `未検出` | 検出の仕組みはあるが、この経路では走っていない |
| `未計測` | その量を持つ概念が上流に無い |

壁面積はこの 3 つで全く違う数になる。`price.py` が「規制対象外」（告示の対象建材で
ない）と「無等級」（第一種発散建築材料）を別のものとして扱うのと同じ思想。

## 合成は最弱が勝つ

1 つの数量を作るのに使った入力の根拠を集め、**一番弱いものをその数量の根拠とする**。
仮定を 1 つでも混ぜた数量は、その仮定の精度までしか正しくない。

平均や加重は採らない。「根拠 3.7」は誰にも説明できず、**見積書の脚注に書けない**。
"""
from __future__ import annotations

from typing import Iterable

#: 根拠の語彙と強さ。**弱いほうが勝つ**
STRENGTH: dict[str, int] = {
    "実測": 5,      # 測った、または作図された実値
    "推定": 4,      # 別の実測から導いた（床外形から面積）
    "代用": 3,      # 別の量で代えた（天井高に壁高、内法に壁芯）
    "既定": 2,      # 上流の既定値（壁厚 120、壁高 2400）
    "外接": 1,      # 外接矩形など、**必ず過大**になる代用
    "未検出": 0,    # 検出の仕組みはあるが、この経路では走っていない
    "未計測": 0,    # その量を持つ概念が上流に無い
}

MEASURED = "実測"

#: 必ず過大になるもの。**1 行でもあれば、その見積りは過大**
OVERSTATES = ("外接",)

#: 数が足りなくなるもの。開口を見ていなければ壁面積が過大、建具の員数は 0
MISSING = ("未検出", "未計測")


def known(value: str) -> bool:
    return value in STRENGTH


def weakest(values: Iterable[str]) -> str:
    """一番弱い根拠。**何も無ければ実測。**"""
    got = [v for v in values if v in STRENGTH]
    if not got:
        return MEASURED
    return min(got, key=lambda v: STRENGTH[v])


def overstates(value: str) -> bool:
    """その根拠に乗った数量は必ず過大か。"""
    return value in OVERSTATES


def weak(value: str) -> bool:
    """実測でないか。"""
    return value != MEASURED
